package com.yiaobang.kserial.utils

import com.yiaobang.kserial.model.TrafficRecorder

/**
 * 把终端录制的问答对生成为设备模拟器 HOCON 配置。
 *
 * 自动推断：
 * - encode：全部字节可打印 → ASCII，否则 HEX；
 * - 分帧：所有帧共享结尾 "\r\n"/"\n"/"\r" → delimiter；否则请求等长 → packSize；否则失败。
 * 生成结果可直接被 DeviceSimulator.createDeviceSimulator 加载。
 */
object SimulatorConfigGenerator {

    /** 模拟器 endpoint 段需要的连接参数。 */
    data class EndpointInfo(
        val port: String,
        val baudRate: Int,
        val dataBits: Int,
        val stopBitsIndex: Int,
        val parityIndex: Int,
        val flowControlIndex: Int
    )

    /** 分帧推断失败，无法生成可用配置。 */
    class FramingNotDeterminable : Exception("无法推断分帧方式：帧尾不统一且请求长度不等")

    fun generate(pairs: List<TrafficRecorder.TrafficPair>, endpoint: EndpointInfo?): String {
        require(pairs.isNotEmpty()) { "没有可用的问答对" }
        val frames = pairs.flatMap { listOf(it.request, it.response) }
        val isText = frames.all { it.isPrintableText() }
        val delimiter = detectDelimiter(frames)
        val packSize = if (delimiter == null && pairs.map { it.request.size }.distinct().size == 1) {
            pairs.first().request.size
        } else {
            null
        }
        if (delimiter == null && packSize == null) throw FramingNotDeterminable()

        return buildString {
            appendLine("# Generated by KSerial traffic recorder.")
            appendLine("# Load it from the Device Simulator page.")
            appendLine("simulator {")
            if (endpoint != null) {
                appendLine("  endpoint {")
                appendLine("    port = \"${endpoint.port}\"")
                appendLine("    baudRate = ${endpoint.baudRate}")
                appendLine("    dataBits = ${endpoint.dataBits}")
                appendLine("    stopBits = ${stopBitsName(endpoint.stopBitsIndex)}")
                appendLine("    parity = \"${parityName(endpoint.parityIndex)}\"")
                appendLine("    flowControl = \"${flowControlName(endpoint.flowControlIndex)}\"")
                appendLine("  }")
                appendLine()
            }
            appendLine("  encode = \"${if (isText) "ASCII" else "HEX"}\"")
            if (delimiter != null) {
                appendLine("  delimiter = \"${escapeHocon(delimiter.toUtf8String())}\"")
            } else {
                appendLine("  packSize = $packSize")
            }
            appendLine()
            appendLine("  rules = [")
            pairs.forEach { pair ->
                val request = pair.content(pair.request, isText)
                val response = pair.content(pair.response, isText)
                appendLine("    { request = $request, response = $response }")
            }
            appendLine("  ]")
            append("}")
        }
    }

    private fun TrafficRecorder.TrafficPair.content(bytes: ByteArray, isText: Boolean): String =
        if (isText) "\"${escapeHocon(bytes.toUtf8String())}\"" else "\"${bytes.toHexDisplayString()}\""

    /** 所有帧必须以同一结尾才认定为 delimiter；仅接受 CR/LF 组合，二进制结尾交给 packSize。 */
    private fun detectDelimiter(frames: List<ByteArray>): ByteArray? {
        val suffix = frames.reduce { acc, next ->
            var len = minOf(acc.size, next.size)
            while (len > 0 && !hasSuffix(acc, next, len)) len--
            acc.takeLast(len).toByteArray()
        }
        val crlf = byteArrayOf('\r'.code.toByte(), '\n'.code.toByte())
        return when {
            suffix.size >= 2 && hasSuffix(suffix, crlf, 2) -> crlf
            suffix.isNotEmpty() && suffix.last() == '\n'.code.toByte() -> byteArrayOf('\n'.code.toByte())
            suffix.isNotEmpty() && suffix.last() == '\r'.code.toByte() -> byteArrayOf('\r'.code.toByte())
            else -> null
        }
    }

    private fun hasSuffix(bytes: ByteArray, reference: ByteArray, length: Int): Boolean {
        if (bytes.size < length || reference.size < length) return false
        for (i in 0 until length) {
            if (bytes[bytes.size - length + i] != reference[reference.size - length + i]) return false
        }
        return true
    }

    private fun ByteArray.isPrintableText(): Boolean = all { byte ->
        val v = byte.toInt() and 0xFF
        v in 0x20..0x7E || v == '\r'.code || v == '\n'.code || v == '\t'.code
    }

    private fun escapeHocon(text: String): String = buildString {
        text.forEach { ch ->
            when (ch) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '\r' -> append("\\r")
                '\n' -> append("\\n")
                '\t' -> append("\\t")
                else -> append(ch)
            }
        }
    }

    private fun stopBitsName(index: Int): String =
        listOf("1", "1.5", "2").getOrElse(index) { "1" }

    private fun parityName(index: Int): String =
        listOf("none", "odd", "even", "mark", "space").getOrElse(index) { "none" }

    private fun flowControlName(index: Int): String =
        listOf("none", "rts/cts", "dsr/dtr", "xon/xoff").getOrElse(index) { "none" }
}
